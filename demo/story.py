"""The plain-language story of NeuroStream, written once and rendered to HTML (dashboard) and Markdown (README).

    .venv/Scripts/python demo/story.py --write-readme     # refreshes the block between the STORY markers in README.md
"""
from __future__ import annotations

import argparse
import html
import re
from pathlib import Path

GOAL_TITLE = "Why does this exist?"
GOAL = [
    "A hospital patient wears a cap that <i>listens</i> to the brain, like a microphone for electricity. "
    "The signal is a wavy line called an <b>EEG</b>. Sometimes it erupts into a storm: a <b>seizure</b>. "
    "No nurse can watch that line every second, for every patient.",

    "<b>This project is a tireless digital watcher.</b> Every second it asks one question: "
    "<i>does this look like a seizure?</i> If yes, it rings an alarm so a doctor can step in. "
    "Nobody can write down what a seizure looks like, so we wrote no rules. "
    "<b>We showed a computer examples and let it learn.</b>",
]
GOAL_NOTE = "A learning project on public research data. Not a medical device."

STEPS_TITLE = "How we built it"
STEPS = [
    ("🧠", "Real examples",
     "500 real brain recordings shared by the University of Bonn: 100 during seizures, 400 calm."),
    ("🔒", "A secret exam",
     "We locked 75 recordings away. The computer never saw them while learning, so it couldn't memorize the answers."),
    ("🎓", "Learning by example",
     "A <b>neural network</b> (a pattern-spotting program) studied about 30,000 labeled one-second snippets. "
     "It guessed, got corrected, and improved, 30 rounds in a row."),
    ("✅", "The exam",
     "On snippets it had never seen, it was right <b>97.6%</b> of the time and caught about "
     "<b>95 of every 100</b> seizure seconds."),
    ("🏭", "An assembly line",
     "Around the model we built the whole chain: a simulated hospital machine, a front desk that checks messages, "
     "a safe mail room, a signal cleaner, the model, and the alarm bell."),
    ("🤖", "A robot inspector",
     "A robot rebuilds everything from scratch in the cloud, replays the secret recordings, and only shows a green "
     "check if the alarms ring at the right moments."),
]
LIMITS = ("Honest note: these recordings are clean and short. Real hospitals are noisier, "
          "and about 5 in 100 seizure seconds were still missed.")

CSS = """
.story{background:var(--card);border:1px solid var(--bd);border-radius:14px;padding:22px 24px;margin-bottom:16px}
.story h2{margin:0 0 12px;font-size:22px}.story p{margin:0 0 12px;max-width:68ch;font-size:16.5px}
.story.hero{border-left:5px solid #2f6fdb}
.story .note{margin:0;color:var(--mut);font-size:14px}
.steps{display:grid;grid-template-columns:repeat(auto-fit,minmax(230px,1fr));gap:12px}
.step{background:var(--bg);border-radius:10px;padding:14px}
.step .ic{font-size:26px;line-height:1}.step b.t{display:block;margin:6px 0 4px}.step span{color:var(--mut);font-size:14.5px}
.limits{margin:14px 0 0;color:var(--mut);font-size:14px}
h2.live{margin:26px 0 10px}
"""


def render_html() -> str:
    goal = "".join(f"<p>{p}</p>" for p in GOAL)
    steps = "".join(f'<div class="step"><div class="ic">{ic}</div><b class="t">{html.escape(t)}</b><span>{b}</span></div>'
                    for ic, t, b in STEPS)
    return (f'<section class="story hero"><h2>{html.escape(GOAL_TITLE)}</h2>{goal}'
            f'<p class="note">{html.escape(GOAL_NOTE)}</p></section>'
            f'<section class="story"><h2>{html.escape(STEPS_TITLE)}</h2><div class="steps">{steps}</div>'
            f'<p class="limits">{html.escape(LIMITS)}</p></section>')


def _md(s: str) -> str:
    return re.sub(r"</?i>", "*", re.sub(r"</?b>", "**", s))


def render_markdown() -> str:
    out = [f"## {GOAL_TITLE}", ""] + [f"{_md(p)}\n" for p in GOAL] + [f"*{GOAL_NOTE}*", "", f"## {STEPS_TITLE}", ""]
    out += [f"{i}. {ic} **{t}.** {_md(b)}" for i, (ic, t, b) in enumerate(STEPS, 1)]
    out += ["", f"*{LIMITS}*"]
    return "\n".join(out) + "\n"


START, END = "<!-- STORY:START (generated by demo/story.py, edit it there) -->", "<!-- STORY:END -->"


def write_readme(path: Path) -> None:
    text = path.read_text(encoding="utf-8")
    block = f"{START}\n{render_markdown()}{END}"
    text = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, text, flags=re.S)
    path.write_text(text, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--write-readme", action="store_true")
    if ap.parse_args().write_readme:
        write_readme(Path(__file__).resolve().parents[1] / "README.md")
        print("README.md updated")
